// Pannello anatomia: abbassa/alza (tocco e trascinamento) e spazio dato al modello
import { serve, launch } from './lib.mjs';
const { srv, url } = await serve();
const { browser, page, errors } = await launch({ w: 412, h: 892 });
let bad = 0;
const ok = (c, m) => { console.log(c ? 'ok  ' : 'KO  ', m); if (!c) bad++; };
await page.goto(url + '/#/anatomia');
await page.waitForSelector('#dock'); await page.waitForTimeout(2500);
const h = async () => { await page.waitForTimeout(600); await page.waitForFunction(() => { const d = document.querySelector('#dock'); return !d.getAnimations().length; }, null, { timeout: 15000 }).catch(() => {}); return page.evaluate(() => ({ dock: document.querySelector('#dock').getBoundingClientRect().height, stage: document.querySelector('#stage').getBoundingClientRect().height, cls: document.querySelector('#dock').className, sx: document.querySelector('#dock').scrollLeft })); };
const a = await h(); console.log(a);
const g = await page.locator('[data-grab]').boundingBox();
await page.mouse.click(g.x + g.width / 2, g.y + g.height / 2); await page.waitForTimeout(2500);
const b = await h(); console.log(b);
ok(b.cls.includes('collapsed') && b.dock < 70 && b.stage > a.stage + 100, 'tocco sulla maniglia: pannello abbassato, modello piu\' grande');
const g2 = await page.locator('[data-grab]').boundingBox();
await page.mouse.click(g2.x + g2.width / 2, g2.y + g2.height / 2); await page.waitForTimeout(2500);
const c = await h(); ok(!c.cls.includes('collapsed') && c.dock > 150, 'secondo tocco: pannello normale');
const g3 = await page.locator('[data-grab]').boundingBox();
await page.mouse.move(g3.x + 100, g3.y + 10); await page.mouse.down(); await page.mouse.move(g3.x + 100, g3.y + 80, { steps: 6 }); await page.mouse.up(); await page.waitForTimeout(2500);
const d = await h(); ok(d.cls.includes('collapsed'), 'trascinando verso il basso: abbassato');
const g4 = await page.locator('[data-grab]').boundingBox();
await page.mouse.move(g4.x + 100, g4.y + 10); await page.mouse.down(); await page.mouse.move(g4.x + 100, g4.y - 120, { steps: 8 }); await page.mouse.up(); await page.waitForTimeout(2500);
const e = await h(); console.log(e); ok(!e.cls.includes('collapsed'), 'trascinando verso l\'alto: riaperto');
ok(e.sx === 0, 'nessuno scorrimento orizzontale del pannello');
await page.locator('[data-grab]').click(); await page.waitForTimeout(600);
await page.screenshot({ path: '/tmp/anat_collapsed.png' });
ok(errors.length === 0, 'nessun errore in console ' + errors.join('|'));
await browser.close(); srv.close();
console.log(bad ? 'FALLITO' : 'Tutti i test superati'); process.exit(bad ? 1 : 0);
