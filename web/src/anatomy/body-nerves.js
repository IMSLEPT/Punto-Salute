// Sistema nervoso: encefalo, midollo spinale, nervi periferici principali.
import { tube, ellipsoid, merge, mirrorX, rng } from './geo.js';
import { spineZ } from './shape.js';

const NERVE = '#f2c230';

export function buildNerves(add) {
  // ---------------------------------------------------------------- encefalo
  const hemi = (s) => ellipsoid(0.040, 0.060, 0.080, { at: [s * 0.0285, 1.676, -0.005], rot: [0.04, 0, 0], seg: 36, hseg: 26, noise: 0.035, seed: 3 + s, freq: 6 });
  add('cervello', ['nervoso', 'organi'], merge([hemi(-1), hemi(1)]), { color: '#dcaaa6', roughness: 0.65 });
  add('cervelletto', ['nervoso', 'organi'], ellipsoid(0.046, 0.026, 0.036, { at: [0, 1.622, -0.062], seg: 24, hseg: 14, noise: 0.03, seed: 9, freq: 8 }), { color: '#c78f8b', roughness: 0.65 });
  add('tronco-encefalico', ['nervoso', 'organi'], tube([[0, 1.650, -0.012], [0, 1.618, -0.026], [0, 1.585, -0.036], [0, 1.555, -0.040]], [0.016, 0.013, 0.012, 0.0095], { radial: 14 }), { color: '#e6c4b3' });

  // midollo spinale + cauda equina
  const cord = [];
  for (let y = 1.555; y >= 1.140; y -= 0.045) cord.push([0, y, spineZ(y) - (y > 1.44 ? 0.016 : 0.025)]);
  add('midollo-spinale', ['nervoso'], tube(cord, [0.0075, 0.0075, 0.0085, 0.0095, 0.009, 0.008, 0.0075, 0.007, 0.0045], { radial: 10, ends: 'round' }), { color: '#f1e2b4' });
  const r = rng(3);
  const strands = [];
  for (let i = 0; i < 9; i++) {
    const dx = (i - 4) * 0.0035;
    strands.push(tube([[0, 1.150, spineZ(1.15) - 0.026], [dx, 1.05, spineZ(1.05) - 0.030], [dx * 1.6 + (r() - 0.5) * 0.004, 0.96, spineZ(0.96) - 0.032], [dx * 2.2, 0.90, -0.078]], 0.0014, { radial: 4, segs: 12 }));
  }
  add('midollo-spinale', ['nervoso'], merge(strands), { color: '#f1e2b4' });

  // ---------------------------------------------------------------- nervi periferici (definiti a sinistra, specchiati)
  const both = (geos) => { const g = merge(geos); return merge([g, mirrorX(g)]); };
  add('plesso-brachiale', ['nervoso'], both([
    tube([[0.016, 1.480, -0.038], [0.060, 1.456, -0.022], [0.110, 1.438, -0.004], [0.170, 1.412, 0.006], [0.206, 1.370, 0.002]], 0.0045, { radial: 8, segs: 18 }),
    tube([[0.018, 1.470, -0.038], [0.070, 1.440, -0.016], [0.130, 1.420, 0.0], [0.200, 1.372, 0.0]], 0.0035, { radial: 8, segs: 14 }),
    tube([[0.020, 1.455, -0.040], [0.080, 1.425, -0.012], [0.150, 1.400, 0.0], [0.204, 1.366, -0.004]], 0.0035, { radial: 8, segs: 14 }),
    // nervo mediano
    tube([[0.206, 1.366, 0.004], [0.218, 1.300, 0.012], [0.240, 1.190, 0.016], [0.252, 1.122, 0.022], [0.280, 1.000, 0.016], [0.300, 0.880, 0.020], [0.310, 0.832, 0.018]], 0.0030, { radial: 6, segs: 24 }),
    // ulnare
    tube([[0.204, 1.366, -0.006], [0.222, 1.290, -0.006], [0.240, 1.190, -0.014], [0.246, 1.120, -0.016], [0.272, 1.010, -0.002], [0.298, 0.890, 0.0], [0.312, 0.834, -0.002]], 0.0030, { radial: 6, segs: 24 }),
    // radiale
    tube([[0.204, 1.362, -0.014], [0.226, 1.290, -0.030], [0.246, 1.200, -0.026], [0.262, 1.130, 0.020], [0.282, 1.020, 0.036], [0.302, 0.900, 0.030]], 0.0030, { radial: 6, segs: 24 }),
  ]), { color: NERVE });

  add('nervo-femorale', ['nervoso'], both([
    tube([[0.040, 1.080, -0.054], [0.050, 1.010, -0.040], [0.070, 0.940, 0.0], [0.086, 0.890, 0.040], [0.090, 0.800, 0.050], [0.092, 0.700, 0.050], [0.090, 0.560, 0.046]], 0.0040, { radial: 8, segs: 26 }),
  ]), { color: NERVE });
  add('nervo-sciatico', ['nervoso'], both([
    tube([[0.036, 0.960, -0.068], [0.060, 0.900, -0.074], [0.084, 0.860, -0.052], [0.092, 0.760, -0.040], [0.096, 0.620, -0.032], [0.097, 0.520, -0.032]], 0.0066, { radial: 10, segs: 26 }),
    tube([[0.097, 0.520, -0.032], [0.092, 0.400, -0.030], [0.088, 0.250, -0.020], [0.082, 0.110, -0.008]], 0.0038, { radial: 8, segs: 18 }),
    tube([[0.097, 0.520, -0.032], [0.116, 0.480, -0.022], [0.124, 0.400, 0.0], [0.114, 0.300, 0.028], [0.108, 0.190, 0.040]], 0.0034, { radial: 8, segs: 16 }),
  ]), { color: NERVE });
  add('nervo-vago', ['nervoso'], both([
    tube([[0.024, 1.588, -0.012], [0.032, 1.540, 0.004], [0.036, 1.470, 0.010], [0.036, 1.420, 0.006], [0.028, 1.360, -0.006], [0.020, 1.300, -0.026], [0.012, 1.230, -0.040], [0.008, 1.160, -0.034], [0.012, 1.110, -0.014]], 0.0026, { radial: 6, segs: 40 }),
  ]), { color: '#f7d56a' });
}
